def top_k_overlap(results, k):
    actual_top = set(
        results.nlargest(k, "CPUE")[
            "FISHING_GROUND_CODE"
        ]
    )

    predicted_top = set(
        results.nlargest(k, "PRED_CPUE")[
            "FISHING_GROUND_CODE"
        ]
    )

    overlap = actual_top.intersection(predicted_top)

    return {
        "K": k,
        "Actual_Top_K": len(actual_top),
        "Predicted_Top_K": len(predicted_top),
        "Correct": len(overlap),
        "Overlap_%": 100 * len(overlap) / k
    }


