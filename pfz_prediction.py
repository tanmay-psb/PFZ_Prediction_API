# Function to get nearest SST for a fishing observation
def get_nearest_sst(row):
    year = int(row["YEAR"])
    month = int(row["MONTH_START"])

    # SST dates belonging to same year and month
    matching_times = sst_times[
        (sst_times.year == year) &
        (sst_times.month == month)
    ]

    if len(matching_times) == 0:
        return np.nan

    # Pick SST date closest to the beginning of the fishing month
    target_date = pd.Timestamp(year=year, month=month, day=1)

    nearest_time = matching_times[
        np.argmin(np.abs(matching_times - target_date))
    ]

    # Extract nearest spatial grid cell
    value = sst["SST"].sel(
        time=nearest_time,
        latitude=row["CENTER_LAT"],
        longitude=row["CENTER_LON"],
        method="nearest"
    ).values

    return float(value)


