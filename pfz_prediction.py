# Check whether nearby SST cells can recover the missing observations

def nearby_sst_check(row, radius=1):
    year = int(row["YEAR"])
    month = int(row["MONTH_START"])

    matching_times = sst_times[
        (sst_times.year == year) &
        (sst_times.month == month)
    ]

    if len(matching_times) == 0:
        return np.nan

    target_date = pd.Timestamp(year=year, month=month, day=1)

    nearest_time = matching_times[
        np.argmin(np.abs(matching_times - target_date))
    ]

    # Find nearest grid indices
    lat_idx = int(
        np.abs(sst.latitude.values - row["CENTER_LAT"]).argmin()
    )
    lon_idx = int(
        np.abs(sst.longitude.values - row["CENTER_LON"]).argmin()
    )

    lat_start = max(0, lat_idx - radius)
    lat_end = min(len(sst.latitude), lat_idx + radius + 1)

    lon_start = max(0, lon_idx - radius)
    lon_end = min(len(sst.longitude), lon_idx + radius + 1)

    neighborhood = sst["SST"].sel(
        time=nearest_time
    ).isel(
        latitude=slice(lat_start, lat_end),
        longitude=slice(lon_start, lon_end)
    ).values

    valid = neighborhood[~np.isnan(neighborhood)]

    return len(valid)


