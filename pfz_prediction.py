def predict_top_10(year, month):
    """
    Predict and rank the 10 most productive fishing grounds
    for the requested year and month.
    """

    # Candidate grounds from our historical data
    candidates = combined[
        ["FISHING_GROUND_CODE", "CENTER_LAT", "CENTER_LON"]
    ].drop_duplicates("FISHING_GROUND_CODE").copy()

    # Keep grounds inside SST coverage
    candidates = candidates[
        candidates["CENTER_LAT"].between(2.5, 20.0) &
        candidates["CENTER_LON"].between(65.5, 95.5)
    ].copy()

    # Find SST for each candidate
    predictions = []

    for _, row in candidates.iterrows():

        month_data = ds.sel(
            time=ds.time.where(
                (ds.time.dt.year == year) &
                (ds.time.dt.month == month),
                drop=True
            )
        )

        if len(month_data.time) == 0:
            continue

        point = month_data["SST"].sel(
            latitude=row["CENTER_LAT"],
            longitude=row["CENTER_LON"],
            method="nearest"
        )

        sst_value = float(point.mean(skipna=True).values)

        if np.isnan(sst_value):
            continue

        # Predict for BOTH fisheries
        for species_group in ["TUNA", "BILLFISH"]:

            for gear in combined["GEAR"].unique():

                predictions.append({
                    "FISHING_GROUND_CODE":
                        row["FISHING_GROUND_CODE"],
                    "CENTER_LAT":
                        row["CENTER_LAT"],
                    "CENTER_LON":
                        row["CENTER_LON"],
                    "SST": sst_value,
                    "MONTH_SIN":
                        np.sin(2 * np.pi * month / 12),
                    "MONTH_COS":
                        np.cos(2 * np.pi * month / 12),
                    "GEAR": gear,
                    "SPECIES_GROUP":
                        species_group
                })

    prediction_df = pd.DataFrame(predictions)

    prediction_df["PRED_LOG_CPUE"] = rf_model.predict(
        prediction_df[features]
    )

    prediction_df["PRED_CPUE"] = np.exp(
        prediction_df["PRED_LOG_CPUE"]
    )

    # Average predictions across gear/species combinations
    top10 = (
        prediction_df
        .groupby(
            [
                "FISHING_GROUND_CODE",
                "CENTER_LAT",
                "CENTER_LON"
            ],
            as_index=False
        )
        .agg(
            PREDICTED_PRODUCTIVITY=("PRED_CPUE", "mean")
        )
        .sort_values(
            "PREDICTED_PRODUCTIVITY",
            ascending=False
        )
        .head(10)
        .reset_index(drop=True)
    )

    top10.insert(0, "RANK", range(1, len(top10) + 1))

    return top10

