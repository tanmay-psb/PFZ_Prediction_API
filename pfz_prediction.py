def predict_all_grounds(year, month, gear):

    candidates = fish_geo_valid[
        fish_geo_valid["FISHING_GROUND_CODE"].notna() &
        fish_geo_valid["CENTER_LAT"].notna() &
        fish_geo_valid["CENTER_LON"].notna()
    ][
        [
            "FISHING_GROUND_CODE",
            "CENTER_LAT",
            "CENTER_LON"
        ]
    ].drop_duplicates(
        "FISHING_GROUND_CODE"
    ).copy()

    # SST coverage
    candidates = candidates[
        candidates["CENTER_LAT"].between(
            float(sst.latitude.min()),
            float(sst.latitude.max())
        ) &
        candidates["CENTER_LON"].between(
            float(sst.longitude.min()),
            float(sst.longitude.max())
        )
    ].copy()

    # Find SST dates in requested month
    matching_times = sst_times[
        (sst_times.year == year) &
        (sst_times.month == month)
    ]

    if len(matching_times) == 0:
        return pd.DataFrame()

    target_date = pd.Timestamp(
        year=year,
        month=month,
        day=1
    )

    nearest_time = matching_times[
        np.argmin(
            np.abs(matching_times - target_date)
        )
    ]

    # Extract SST
    def extract_sst(row):
        return float(
            sst["SST"].sel(
                time=nearest_time,
                latitude=row["CENTER_LAT"],
                longitude=row["CENTER_LON"],
                method="nearest"
            ).values
        )

    candidates["SST"] = candidates.apply(
        extract_sst,
        axis=1
    )

    candidates = candidates.dropna(
        subset=["SST"]
    ).copy()

    # Seasonal features
    candidates["MONTH_SIN"] = np.sin(
        2 * np.pi * month / 12
    )

    candidates["MONTH_COS"] = np.cos(
        2 * np.pi * month / 12
    )

    candidates["GEAR"] = gear

    # Predict
    candidates["PRED_LOG_CPUE"] = model.predict(
        candidates[feature_columns]
    )

    candidates["PRED_CPUE"] = np.exp(
        candidates["PRED_LOG_CPUE"]
    )

    # Rank ALL candidates
    candidates = candidates.sort_values(
        "PRED_CPUE",
        ascending=False
    ).reset_index(drop=True)

    candidates["PREDICTED_RANK"] = (
        candidates.index + 1
    )

    return candidates

