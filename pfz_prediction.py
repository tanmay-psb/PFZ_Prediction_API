def monthly_top_k_overlap(df, k):
    scores = []

    for (year, month), group in df.groupby(
        ["YEAR", "MONTH_START"]
    ):
        # Skip months with fewer than k grounds
        if len(group) < k:
            continue

        actual_top = set(
            group.nlargest(k, "ACTUAL_CPUE")[
                "FISHING_GROUND_CODE"
            ]
        )

        predicted_top = set(
            group.nlargest(k, "PRED_CPUE")[
                "FISHING_GROUND_CODE"
            ]
        )

        correct = len(
            actual_top.intersection(predicted_top)
        )

        scores.append({
            "YEAR": year,
            "MONTH": month,
            "GROUNDS": len(group),
            "CORRECT": correct,
            "OVERLAP_%": 100 * correct / k
        })

    return pd.DataFrame(scores)


